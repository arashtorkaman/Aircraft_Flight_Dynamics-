function export_phase3_results(results, cfg)
%EXPORT_PHASE3_RESULTS Save numerical Phase 3 results to MAT and Markdown.

if ~cfg.output.save_results
    return
end

if ~exist(cfg.paths.results_dir,'dir')
    mkdir(cfg.paths.results_dir);
end

mat_path = fullfile(cfg.paths.results_dir,'phase3_results.mat');
save(mat_path,'results');

md_path = fullfile(cfg.paths.results_dir,'phase3_results_generated.md');
fid = fopen(md_path,'w');

if fid < 0
    error('Could not open %s for writing.',md_path);
end

cleanup = onCleanup(@() fclose(fid));

fprintf(fid,'# Phase 3 — Generated Numerical Results\n\n');
fprintf(fid,'> Generated by `run_phase3.m`. Review assumptions before publication.\n\n');

fprintf(fid,'## Open-Loop Baseline\n\n');
fprintf(fid,'Controllability rank: `%d / %d`\n\n', ...
    results.baseline.controllability_rank, size(results.model.A,1));

fprintf(fid,'### Open-loop poles\n\n');
fprintf(fid,'```text\n');
for k = 1:numel(results.baseline.open_loop_poles)
    p = results.baseline.open_loop_poles(k);
    fprintf(fid,'% .8f %+.8fi\n',real(p),imag(p));
end
fprintf(fid,'```\n\n');

fprintf(fid,'## LQR\n\n');
fprintf(fid,'### Q\n\n```text\n');
write_matrix(fid,results.lqr.Q);
fprintf(fid,'```\n\n');

fprintf(fid,'### R\n\n```text\n');
write_matrix(fid,results.lqr.R);
fprintf(fid,'```\n\n');

fprintf(fid,'### K\n\n```text\n');
write_matrix(fid,results.lqr.K);
fprintf(fid,'```\n\n');

fprintf(fid,'### LQR poles\n\n```text\n');
for k = 1:numel(results.lqr.poles)
    p = results.lqr.poles(k);
    fprintf(fid,'% .8f %+.8fi\n',real(p),imag(p));
end
fprintf(fid,'```\n\n');

if isfield(results,'pitch_lqr')
    r = results.pitch_lqr;

    fprintf(fid,'## Pitch Tracking — LQR\n\n');
    fprintf(fid,'| Metric | Value |\n');
    fprintf(fid,'|---|---:|\n');
    fprintf(fid,'| Rise time | %.8g s |\n',r.rise_time);
    fprintf(fid,'| Settling time | %.8g s |\n',r.settling_time);
    fprintf(fid,'| Overshoot | %.8g %% |\n',r.overshoot_percent);
    fprintf(fid,'| Steady-state error | %.8g rad |\n',r.steady_state_error);
    fprintf(fid,'| Peak pitch rate | %.8g rad/s |\n',r.peak_pitch_rate_rad_s);
    fprintf(fid,'| Peak elevator | %.8g deg |\n\n',r.peak_elevator_deg);
end

if isfield(results,'altitude_lqr')
    fprintf(fid,'## Altitude Tracking — LQR Autopilot\n\n');

    if isfield(results.altitude_lqr,'available') && ...
            ~results.altitude_lqr.available
        fprintf(fid,'Not yet populated: %s\n\n',results.altitude_lqr.reason);
    else
        r = results.altitude_lqr;
        fprintf(fid,'| Metric | Value |\n');
        fprintf(fid,'|---|---:|\n');
        fprintf(fid,'| Rise time | %.8g s |\n',r.rise_time);
        fprintf(fid,'| Settling time | %.8g s |\n',r.settling_time);
        fprintf(fid,'| Overshoot | %.8g %% |\n',r.overshoot_percent);
        fprintf(fid,'| Steady-state error | %.8g m |\n',r.steady_state_error);
        fprintf(fid,'| Peak pitch | %.8g deg |\n',r.peak_pitch_deg);
        fprintf(fid,'| Peak elevator | %.8g deg |\n\n',r.peak_elevator_deg);
    end
end

fprintf(fid,'## Controller Comparison\n\n');
fprintf(fid,'| Controller | Stable | Dominant real pole | Minimum pole damping |\n');
fprintf(fid,'|---|---:|---:|---:|\n');

T = results.comparison;
for k = 1:height(T)
    fprintf(fid,'| %s | %d | %.8g | %.8g |\n', ...
        T.Controller(k), T.Stable(k), ...
        T.DominantRealPole(k), T.MinimumPoleDamping(k));
end

fprintf('Saved numerical results:\n  %s\n  %s\n',mat_path,md_path);

end

function write_matrix(fid,M)

for r = 1:size(M,1)
    for c = 1:size(M,2)
        fprintf(fid,'% .10g',M(r,c));
        if c < size(M,2)
            fprintf(fid,'  ');
        end
    end
    fprintf(fid,'\n');
end

end
